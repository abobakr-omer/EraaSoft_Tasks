-- Secure Banking System - database script (Oracle)
-- Tables are normally created by Hibernate (spring.jpa.hibernate.ddl-auto=update).
-- Run this script only if you want to create the tables and reference data by hand.
-- Demo users are created by DataInitializer (their passwords must be BCrypt-hashed by the app).

-- ---------- Tables ----------
CREATE TABLE permissions (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL UNIQUE
);

CREATE TABLE roles (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL UNIQUE
);

CREATE TABLE role_permission (
    role_id       NUMBER NOT NULL REFERENCES roles(id),
    permission_id NUMBER NOT NULL REFERENCES permissions(id),
    CONSTRAINT uk_role_permission UNIQUE (role_id, permission_id)
);

CREATE TABLE customers (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    VARCHAR2(255) NOT NULL,
    email        VARCHAR2(255) NOT NULL UNIQUE,
    password     VARCHAR2(255) NOT NULL,          -- BCrypt hash only
    phone_number VARCHAR2(255),
    enabled      NUMBER(1) DEFAULT 1 NOT NULL,
    blocked      NUMBER(1) DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP NOT NULL
);

CREATE TABLE customer_role (
    customer_id NUMBER NOT NULL REFERENCES customers(id),
    role_id     NUMBER NOT NULL REFERENCES roles(id),
    CONSTRAINT uk_customer_role UNIQUE (customer_id, role_id)
);

CREATE TABLE accounts (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR2(255) NOT NULL UNIQUE,
    balance        NUMBER(19,2) NOT NULL,
    currency       VARCHAR2(3) NOT NULL,
    status         VARCHAR2(20) NOT NULL,         -- ACTIVE, BLOCKED, CLOSED
    customer_id    NUMBER NOT NULL REFERENCES customers(id)
);

CREATE TABLE transfers (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount          NUMBER(19,2) NOT NULL,
    status          VARCHAR2(20) NOT NULL,        -- PENDING, APPROVED, REJECTED, COMPLETED, CANCELLED
    created_at      TIMESTAMP NOT NULL,
    from_account_id NUMBER NOT NULL REFERENCES accounts(id),
    to_account_id   NUMBER NOT NULL REFERENCES accounts(id),
    created_by      NUMBER NOT NULL REFERENCES customers(id)
);

